#!/usr/bin/env python3
"""Generate app themes (vivid, bat, starship) from terminal color schemes.

Reads $XDG_CONFIG_HOME/colorschemes/themes.toml, a [themes] table mapping each
theme name to a color scheme, or to { scheme = ..., targets = [...] } to
generate for only some of vivid, bat, and starship, and writes, for each theme:

  $XDG_CONFIG_HOME/vivid/themes/<name>.yml                (LS_COLORS)
  $XDG_CONFIG_HOME/bat/themes/<name>.tmTheme              (syntax highlighting)
  $XDG_CONFIG_HOME/starship/palettes/<name>.palette.toml  (prompt palette)

A scheme name resolves to $XDG_CONFIG_HOME/colorschemes/iterm2/<scheme>.itermcolors,
or, for '<scheme> (Dark)' and '<scheme> (Light)', to that variant of a file
holding both; failing that, to the Ghostty theme colorschemes/ghostty/<scheme>.
Starship palette names use underscores in place of hyphens.

Each target shares one template; only the palette differs. Each accent is the
normal or bright ANSI variant, whichever reads better against the scheme's
background, blended toward the foreground if it still falls short of a minimum
contrast, so light and dark schemes both work.

The .tmTheme files under $XDG_CONFIG_HOME/colorschemes/{textmate,sublime} are
also linked into bat's themes, and bat's cache is rebuilt when anything
changed. Generated files and links no longer called for are removed; files
this script did not generate are never overwritten.
"""

