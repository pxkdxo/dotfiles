def rgb(color: dict[str, float]) -> RGB:
    return (
        color["Red Component"],
        color["Green Component"],
        color["Blue Component"],
    )


def mix(a: RGB, b: RGB, t: float) -> RGB:
    """Blend `t` of `b` into `a`."""
    return (
        a[0] + (b[0] - a[0]) * t,
        a[1] + (b[1] - a[1]) * t,
        a[2] + (b[2] - a[2]) * t,
    )


def luminance(c: RGB) -> float:
    def channel(v: float) -> float:
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(v) for v in c)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: RGB, b: RGB) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def hex_color(c: RGB) -> str:
    return "".join(f"{round(min(max(v, 0.0), 1.0) * 255):02x}" for v in c)


@dataclass(frozen=True, kw_only=True)
class Scheme:
    label: str
    background: RGB
    foreground: RGB
    ansi: tuple[RGB, ...]
    selection: RGB | None = None
    selected_text: RGB | None = None
    cursor: RGB | None = None
    cursor_text: RGB | None = None


def load_iterm2(path: Path, variant: str = "") -> Scheme:
    data: dict[str, dict[str, float]] = plistlib.loads(path.read_bytes())

    def color(key: str) -> RGB | None:
        found = data.get(f"{key}{variant}") or data.get(key)
        return rgb(found) if found else None

    def required(key: str) -> RGB:
        if (found := color(key)) is None:
            raise KeyError(key)
        return found

    return Scheme(
        label=f"iTerm2 scheme {path.stem}{variant}",
        background=required("Background Color"),
        foreground=required("Foreground Color"),
        ansi=tuple(required(f"Ansi {n} Color") for n in range(16)),
        selection=color("Selection Color"),
        selected_text=color("Selected Text Color"),
        cursor=color("Cursor Color"),
        cursor_text=color("Cursor Text Color"),
    )


def parse_hex(value: str) -> RGB:
    digits = value.strip().strip('"').removeprefix("#")
    if len(digits) != 6:
        raise ValueError(f"not a hex color: {value!r}")
    return (
        int(digits[0:2], 16) / 255,
        int(digits[2:4], 16) / 255,
        int(digits[4:6], 16) / 255,
    )


def load_ghostty(path: Path) -> Scheme:
    values: dict[str, str] = {}
    ansi: dict[int, RGB] = {}
    for line in path.read_text().splitlines():
        key, sep, value = line.partition("=")
        if not sep or line.lstrip().startswith("#"):
            continue
        if key.strip() == "palette":
            index, _, hex_value = value.partition("=")
            ansi[int(index)] = parse_hex(hex_value)
        else:
            values[key.strip()] = value.strip()

    def color(key: str) -> RGB | None:
        return parse_hex(values[key]) if key in values else None

    return Scheme(
        label=f"Ghostty theme {path.name}",
        background=parse_hex(values["background"]),
        foreground=parse_hex(values["foreground"]),
        ansi=tuple(ansi[n] for n in range(16)),
        selection=color("selection-background"),
        selected_text=color("selection-foreground"),
        cursor=color("cursor-color"),
        cursor_text=color("cursor-text"),
    )


def load_scheme(name: str) -> Scheme:
    itermcolors = ITERM2_SCHEMES / f"{name}.itermcolors"
    if itermcolors.is_file():
        return load_iterm2(itermcolors)
    for variant in VARIANTS:
        base = ITERM2_SCHEMES / f"{name.removesuffix(variant)}.itermcolors"
        if name.endswith(variant) and base.is_file():
            return load_iterm2(base, variant)
    ghostty = GHOSTTY_SCHEMES / name
    if ghostty.is_file():
        return load_ghostty(ghostty)
    raise FileNotFoundError(f"no iTerm2 or Ghostty scheme named '{name}'")


def palette(scheme: Scheme) -> Palette:
    bg, fg, ansi = scheme.background, scheme.foreground, scheme.ansi

    def legible(c: RGB, minimum: float = MIN_CONTRAST) -> RGB:
        """Blend `c` toward the foreground until it reaches `minimum` contrast."""
        t = 0.0
        while contrast(mix(c, fg, t), bg) < minimum and t < 1.0:
            t += 0.05
        return mix(c, fg, min(t, 1.0))

    def readable(n: int) -> RGB:
        return legible(max(ansi[n], ansi[n + 8], key=lambda c: contrast(c, bg)))

    colors = {name: readable(n) for name, n in ACCENTS.items()}
    gray = ansi[8]
    dimmer_than_text = contrast(gray, bg) < contrast(fg, bg)
    muted = gray if dimmer_than_text else mix(fg, bg, 0.45)
    return {
        "base": bg,
        "fg": fg,
        "muted": legible(muted, MIN_MUTED_CONTRAST),
        **colors,
        "orange": legible(mix(colors["red"], colors["yellow"], 0.5)),
        "pink": legible(mix(colors["magenta"], colors["red"], 0.35)),
        "selection": scheme.selection or mix(bg, fg, 0.2),
        "line": mix(bg, fg, 0.06),
    }


def render_vivid(_name: str, scheme: Scheme, colors: Palette) -> str:
    names = ("base", "fg", "muted", *ACCENTS, "orange", "pink")
    lines = "\n".join(f'  {name}: "{hex_color(colors[name])}"' for name in names)
    return f"# {MARKER} from {scheme.label}\n\ncolors:\n{lines}\n\n{VIVID_TEMPLATE}"


def render_tmtheme(name: str, scheme: Scheme, colors: Palette) -> str:
    def color(key: str) -> str:
        return f"#{hex_color(colors[key])}"

    general = {
        "background": color("base"),
        "foreground": color("fg"),
        "caret": color("fg"),
        "selection": color("selection"),
        "lineHighlight": color("line"),
        "gutter": color("base"),
        "gutterForeground": color("muted"),
        "invisibles": color("muted"),
        "findHighlight": color("yellow"),
        "findHighlightForeground": color("base"),
    }
    rules = [
        {
            "name": rule,
            "scope": scope,
            "settings": {
                "foreground": color(key),
                **({"fontStyle": style} if style else {}),
            },
        }
        for rule, scope, key, style in TMTHEME_SCOPES
    ]
    rules.append(
        {
            "name": "Invalid",
            "scope": "invalid",
            "settings": {"foreground": color("base"), "background": color("red")},
        }
    )
    theme = {
        "name": name,
        "comment": f"{MARKER} from {scheme.label}",
        "settings": [{"settings": general}, *rules],
    }
    return plistlib.dumps(theme, fmt=plistlib.FMT_XML).decode()


def starship_name(name: str) -> str:
    return name.replace("-", "_")


def render_starship(name: str, scheme: Scheme, colors: Palette) -> str:
    """Render the palette keys the starship themes share."""
    bg, fg, ansi = colors["base"], colors["fg"], scheme.ansi
    entries: Palette = {
        "background": bg,
        "background_alt": colors["line"],
        "foreground": fg,
        "black": ansi[0],
        "white": ansi[7],
        **{accent: colors[accent] for accent in ACCENTS},
        "purple": colors["magenta"],
        "teal": colors["cyan"],
        "orange": colors["orange"],
        "pink": colors["pink"],
        "grey": colors["muted"],
        "light_black": ansi[8],
        "light_white": ansi[15],
        "light_fg": fg,
        **{f"light_{accent}": ansi[n + 8] for accent, n in ACCENTS.items()},
        "dim_black": mix(ansi[0], bg, 0.5),
        "dim_white": mix(ansi[7], bg, 0.2),
        "dim_fg": mix(fg, bg, 0.2),
        **{f"dim_{accent}": mix(colors[accent], bg, 0.2) for accent in ACCENTS},
        "cursor_bg": scheme.cursor or fg,
        "cursor_fg": scheme.cursor_text or bg,
        "selection_bg": colors["selection"],
        "selection_fg": scheme.selected_text or fg,
        "highlight_bg": colors["selection"],
        "highlight_fg": fg,
    }
    lines = "\n".join(
        f'{key} = "#{hex_color(c)}"' for key, c in sorted(entries.items())
    )
    header = f"# {MARKER} from {scheme.label}"
    return f'{header}\n[palettes."{starship_name(name)}"]\n{lines}\n'


@dataclass(frozen=True)
class Target:
    name: str
    directory: Path
    suffix: str
    render: Callable[[str, Scheme, Palette], str]
    stem: Callable[[str], str] = lambda name: name

    def path(self, name: str) -> Path:
        return self.directory / f"{self.stem(name)}{self.suffix}"


TARGETS: Final = (
    Target("vivid", VIVID_THEMES, ".yml", render_vivid),
    Target("bat", BAT_THEMES, ".tmTheme", render_tmtheme),
    Target(
        "starship", STARSHIP_PALETTES, ".palette.toml", render_starship, starship_name
    ),
)


@dataclass(frozen=True)
class Theme:
    name: str
    scheme: str
    targets: tuple[Target, ...]


def load_themes() -> list[Theme]:
    with CONFIG.open("rb") as f:
        entries: dict[str, str | dict[str, Any]] = tomllib.load(f)["themes"]
    by_name = {target.name: target for target in TARGETS}
    themes: list[Theme] = []
    for name, entry in entries.items():
        if isinstance(entry, str):
            themes.append(Theme(name, entry, TARGETS))
            continue
        if unknown := set(entry.get("targets", ())) - by_name.keys():
            raise ValueError(f"theme '{name}': unknown target(s) {sorted(unknown)}")
        targets = tuple(by_name[t] for t in entry.get("targets", by_name))
        themes.append(Theme(name, entry["scheme"], targets))
    return themes


def is_generated(path: Path) -> bool:
    return path.is_file() and not path.is_symlink() and MARKER in path.read_text()


class Writer:
    """Write files and links, or with `dry_run`, only report them."""

    def __init__(self, *, dry_run: bool) -> None:
        self.dry_run: bool = dry_run
        self.changed: set[Path] = set()

    def _note(self, action: str, done: str, path: Path) -> None:
        print(f"{'would ' + action if self.dry_run else done} {path}", flush=True)
        self.changed.add(path.parent)

    def write(self, path: Path, text: str) -> None:
        if path.exists() and not is_generated(path):
            print(f"skipping {path} (not generated by this script)")
            return
        if path.exists() and path.read_text() == text:
            return
        self._note("write", "wrote", path)
        if not self.dry_run:
            _ = path.write_text(text)

    def link(self, path: Path, target: Path) -> None:
        rel = target.relative_to(path.parent, walk_up=True)
        if path.is_symlink() and os.readlink(path) == os.fspath(rel):
            return
        if path.exists() and not path.is_symlink():
            print(f"Warning: {path} is a real file; not linking it", file=sys.stderr)
            return
        self._note("link", "linked", path)
        if not self.dry_run:
            path.unlink(missing_ok=True)
            path.symlink_to(rel)

    def remove(self, path: Path) -> None:
        self._note("remove", "removed", path)
        if not self.dry_run:
            path.unlink()


def link_native_tmthemes(writer: Writer, generated: set[Path]) -> None:
    native: dict[str, Path] = {}
    for directory in NATIVE_TMTHEME_DIRS:
        for path in sorted(directory.glob("*.tmTheme")):
            if BAT_THEMES / path.name in generated:
                print(f"Warning: {path} has a generated theme's name; skipping")
            else:
                _ = native.setdefault(path.name, path)
    for name, path in native.items():
        writer.link(BAT_THEMES / name, path)
    for path in sorted(BAT_THEMES.glob("*.tmTheme")):
        if path.is_symlink() and path.name not in native:
            target = Path(os.path.normpath(path.parent / os.readlink(path)))
            if target.parent in NATIVE_TMTHEME_DIRS:
                writer.remove(path)


def main() -> int:
    parser = ArgumentParser(description=(__doc__ or "").partition("\n")[0])
    _ = parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would change without writing themes",
    )
    args = parser.parse_args()
    writer = Writer(dry_run=args.dry_run)

    try:
        themes = load_themes()
    except (OSError, KeyError, TypeError, ValueError) as exc:
        print(f"Error: {CONFIG}: {exc}", file=sys.stderr)
        return 1

    status = 0
    for theme in themes:
        try:
            scheme = load_scheme(theme.scheme)
            colors = palette(scheme)
        except (OSError, KeyError, ValueError, plistlib.InvalidFileException) as exc:
            print(
                f"Error: theme '{theme.name}' from '{theme.scheme}': {exc}",
                file=sys.stderr,
            )
            status = 1
            continue
        for target in theme.targets:
            writer.write(
                target.path(theme.name), target.render(theme.name, scheme, colors)
            )

    for target in TARGETS:
        expected = {target.path(t.name) for t in themes if target in t.targets}
        for path in sorted(target.directory.glob(f"*{target.suffix}")):
            if path not in expected and is_generated(path):
                writer.remove(path)

    bat = TARGETS[1]
    link_native_tmthemes(writer, {bat.path(t.name) for t in themes if bat in t.targets})

    if BAT_THEMES in writer.changed and not args.dry_run:
        # bat reads `cache` as a file name if one exists in the working directory.
        _ = subprocess.run(["bat", "cache", "--build"], cwd=BAT_THEMES, check=True)
    return status


if __name__ == "__main__":
    sys.exit(main())
